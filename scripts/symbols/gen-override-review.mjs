// Emits scripts/symbols/keyword-overrides.pl.review.md — the reviewable form
// of keyword-overrides.pl.json, for the native-speaker check those entries are
// still pending (§19.6 applies per language).
//
// Ordered by how likely the concept is to actually be SEARCHED, not by id:
// each row is ranked by where its English keyword falls in the 30k frequency
// lexicon the app already ships. Reviewing the top of this file covers most of
// the real risk; the tail is `bone densitometry` and `adapted nordic skiing`.
//
// Usage: node scripts/symbols/gen-override-review.mjs

import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..', '..')

const kw = (p) => (p.keywords ?? []).map((k) => k.keyword).filter(Boolean)
const load = (l) =>
  readFile(join(here, 'data', `arasaac-index-${l}.json`), 'utf8').then(JSON.parse)

const [overrides, en, es, lexicon] = await Promise.all([
  readFile(join(here, 'keyword-overrides.pl.json'), 'utf8').then(JSON.parse),
  load('en'),
  load('es'),
  readFile(join(root, 'public', 'prediction', 'en.txt'), 'utf8'),
])

const enM = new Map(en.map((p) => [p._id, kw(p)]))
const esM = new Map(es.map((p) => [p._id, kw(p)]))
const catM = new Map(en.map((p) => [p._id, (p.categories ?? [])[0] ?? '—']))
const rank = new Map(lexicon.split('\n').filter(Boolean).map((w, i) => [w, i]))

// Clock faces are rule-generated and verified by checking the RULE, not the
// 96 strings — they are listed separately rather than mixed into the triage.
const CLOCK = new Set(
  Object.entries(overrides)
    .filter(([id, v]) => !id.startsWith('_') && catM.get(Number(id)) === 'day hours')
    .map(([id]) => id),
)

const rows = []
for (const [id, words] of Object.entries(overrides)) {
  if (id.startsWith('_') || CLOCK.has(id)) continue
  const enWords = enM.get(Number(id)) ?? []
  let best = Infinity
  for (const w of enWords) {
    const r = rank.get(w.toLowerCase())
    if (r !== undefined && r < best) best = r
  }
  rows.push({
    id,
    rank: best,
    en: enWords.slice(0, 3).join(' / ') || '—',
    es: (esM.get(Number(id)) ?? []).slice(0, 2).join(' / ') || '—',
    pl: words.join(' / '),
    cat: catM.get(Number(id)) ?? '—',
  })
}
rows.sort((a, b) => a.rank - b.rank || Number(a.id) - Number(b.id))

const ranked = rows.filter((r) => r.rank < Infinity)
const rest = rows.filter((r) => r.rank === Infinity)

const table = (list) =>
  [
    '| id | English (ARASAAC) | Spanish (ARASAAC) | Polish (ours) | category |',
    '|---|---|---|---|---|',
    ...list.map((r) => `| ${r.id} | ${r.en} | ${r.es} | **${r.pl}** | ${r.cat} |`),
  ].join('\n')

const md = `# Polish symbol keywords — review needed

**What this is.** ARASAAC stopped translating into Polish in 2024: everything
created up to 2020 has Polish keywords, 2025–26 has none, and 1,090 pictograms
were left unsearchable in Polish. These are the keywords we wrote to fill that
gap, in \`keyword-overrides.pl.json\`.

**What is being asked.** Confirm the Polish is right, or correct it. These were
written from ARASAAC's own English and Spanish keywords and have **not** been
checked by a native speaker.

**Why the risk is lower than a board word.** These are SEARCH keywords. They are
never spoken, and never become a button label on their own — the caregiver types
that themselves. A wrong one costs a failed search, or an odd label next to a
picture the reviewer can see. That is why this did not need the never-machine-
translate rule that governs boards. It is still worth checking, because a
misleading label beside a picture can steer someone to the wrong symbol.

**ARASAAC always wins.** The build applies an override only where upstream has
no Polish keyword, so every line here retires itself the moment ARASAAC
translates that pictogram. Nothing here can shadow real ARASAAC data.

## How to review this efficiently

Rows are ordered by **how likely the concept is to be searched** — the rank of
its English keyword in the 30k frequency lexicon the app ships. The first 100
rows carry most of the real risk. The tail is \`bone densitometry\`,
\`adapted nordic skiing\` and \`brachiate\`, and matters much less.

## Known problem in ARASAAC's own data

For the weekday entries (39717–39730) ARASAAC's **English and Spanish disagree
by one day** — 39717 is keyworded \`next Saturday\` in English but
\`próximo domingo\` in Spanish. Spanish is ARASAAC's source language, so the
Polish below follows the Spanish. **Please confirm that was the right call.**

## Clock faces (${CLOCK.size}) — verify the rule, not the strings

Rule-generated by \`gen-clock-keywords.mjs\`. Polish clock time is a rule, and
one that translating from English or Spanish gets wrong: \`03:30\` is
**wpół do czwartej** — "half *to four*" — not "half past three". Check the four
patterns and the whole set follows:

| time | pattern | example |
|---|---|---|
| H:00 | feminine ordinal | \`trzecia\` · \`godzina trzecia\` |
| H:15 | \`po\` + locative | \`kwadrans po trzeciej\` |
| H:30 | \`wpół do\` + genitive of the **next** hour | \`wpół do czwartej\` |
| H:45 | \`za\` + nominative of the **next** hour | \`za kwadrans czwarta\` |

Midnight adds \`północ\`, noon adds \`południe\`, and every entry also carries its
digital form (\`15:00\`) so the 12- and 24-hour pictograms stay separable.

## Ranked by likelihood of being searched (${ranked.length})

${table(ranked)}

## Remaining — no English-frequency signal (${rest.length})

${table(rest)}
`

const out = join(here, 'keyword-overrides.pl.review.md')
await writeFile(out, md)
console.log(
  `${out}: ${ranked.length} ranked + ${rest.length} unranked + ${CLOCK.size} clock`,
)
